import { writeFileSync, readFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCards } from '../data/cards-raw.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const artistPath = join(root, 'data', 'card-artists.json');
const artistMap = existsSync(artistPath)
  ? JSON.parse(readFileSync(artistPath, 'utf8'))
  : {};

const cards = buildCards().map((c) => ({
  ...c,
  artist: artistMap[c.id] || null,
}));
const ms01 = cards.filter((c) => c.set_code === 'MS01');
const iconic = ms01.filter((c) => c.has_iconic);
const withArtist = cards.filter((c) => c.artist).length;

console.log(`MS01: ${ms01.length} (expected 141 — includes Streetkid a/b)`);
console.log(`Iconic-eligible MS01: ${iconic.length} (expected 32)`);
console.log(`Showcase: ${cards.length - ms01.length}`);
console.log(`Artists mapped: ${withArtist}/${cards.length}`);
console.log(
  `Types: L=${ms01.filter((c) => c.type === 'Legend').length} U=${ms01.filter((c) => c.type === 'Unit').length} G=${ms01.filter((c) => c.type === 'Gear').length} P=${ms01.filter((c) => c.type === 'Program').length}`,
);

function sqlStr(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

const values = cards
  .map(
    (c) =>
      `(${[
        sqlStr(c.id),
        sqlStr(c.number),
        sqlStr(c.name),
        sqlStr(c.type),
        sqlStr(c.eurodollars),
        sqlStr(c.rarity),
        sqlStr(c.zone),
        sqlStr(c.zone_slot),
        sqlStr(c.sheet),
        sqlStr(c.face),
        sqlStr(c.row_pos),
        sqlStr(c.band),
        sqlStr(c.has_iconic),
        sqlStr(Boolean(c.has_bstamp)),
        sqlStr(Boolean(c.has_prstamp)),
        sqlStr(c.set_code),
        sqlStr(c.notes),
        sqlStr(c.artist),
        sqlStr(c.sort_order),
      ].join(', ')})`,
  )
  .join(',\n  ');

const seedSql = `-- Auto-generated by scripts/generate-seed.mjs — do not edit by hand
-- MS01 ${ms01.length} + showcase ${cards.length - ms01.length} | Iconic MS01 ${iconic.length}
-- Safe to re-run: upserts cards; does NOT wipe ownership.

insert into public.cards (
  id, number, name, type, eurodollars, rarity,
  zone, zone_slot, sheet, face, row_pos, band,
  has_iconic, has_bstamp, has_prstamp, set_code, notes, artist, sort_order
) values
  ${values}
on conflict (id) do update set
  number = excluded.number,
  name = excluded.name,
  type = excluded.type,
  eurodollars = excluded.eurodollars,
  rarity = excluded.rarity,
  zone = excluded.zone,
  zone_slot = excluded.zone_slot,
  sheet = excluded.sheet,
  face = excluded.face,
  row_pos = excluded.row_pos,
  band = excluded.band,
  has_iconic = excluded.has_iconic,
  has_bstamp = excluded.has_bstamp,
  has_prstamp = excluded.has_prstamp,
  set_code = excluded.set_code,
  notes = excluded.notes,
  artist = excluded.artist,
  sort_order = excluded.sort_order;

-- Placeholder USD prices — refresh with: npm run prices
insert into public.card_prices (card_id, variant, usd, updated_at)
select id, 'base', 0, now() from public.cards
on conflict (card_id, variant) do nothing;

insert into public.card_prices (card_id, variant, usd, updated_at)
select id, 'iconic', 0, now() from public.cards where has_iconic = true
on conflict (card_id, variant) do nothing;
`;

mkdirSync(join(root, 'data'), { recursive: true });
mkdirSync(join(root, 'public', 'data'), { recursive: true });
writeFileSync(join(root, 'data', 'cards.json'), JSON.stringify(cards, null, 2));
copyFileSync(join(root, 'data', 'cards.json'), join(root, 'public', 'data', 'cards.json'));
writeFileSync(join(root, 'supabase', 'seed.sql'), seedSql);

const setupPath = join(root, 'supabase', 'setup-all.sql');
const setup = readFileSync(setupPath, 'utf8');
const schemaEnd = setup.indexOf('-- Auto-generated by scripts/generate-seed.mjs');
if (schemaEnd === -1) {
  throw new Error('setup-all.sql missing seed marker; refuse to overwrite');
}
writeFileSync(setupPath, `${setup.slice(0, schemaEnd).trimEnd()}\n${seedSql}`);
console.log('Wrote data/cards.json, public/data/cards.json, supabase/seed.sql, supabase/setup-all.sql');
